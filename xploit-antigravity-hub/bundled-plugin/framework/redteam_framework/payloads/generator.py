def _safe_import(module_path: str, label: str):
    """Import a module safely, skip if not found."""
    try:
        parts = module_path.rsplit(".", 1)
        mod = __import__(module_path, fromlist=[parts[-1]])
        PAYLOAD_REGISTRY[label] = mod
    except ImportError as e:
        print(f"[!] Could not load {label}: {e}")


