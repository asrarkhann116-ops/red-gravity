def save_payload(payload: str, output_path: str, metadata: dict = None):
    """Save payload to file with optional metadata header."""
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)

    header = ""
    if metadata:
        header = "# " + "=" * 60 + "\n"
        header += f"# Generated by The Forge — {datetime.now().isoformat()}\n"
        for k, v in metadata.items():
            header += f"# {k}: {v}\n"
        header += "# " + "=" * 60 + "\n\n"

    with open(output_path, "w") as f:
        f.write(header + payload)

    print(f"[+] Payload saved to: {output_path}")
    print(f"    Size: {len(payload)} bytes")


