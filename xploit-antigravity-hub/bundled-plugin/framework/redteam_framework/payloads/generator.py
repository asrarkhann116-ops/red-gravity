def apply_encoding(payload: str, encoding: str, key: Optional[bytes] = None) -> str:
    """Apply encoding/obfuscation to a payload string."""
    raw = payload.encode()

    if encoding == "none":
        return payload

    if encoding == "base64":
        return b64_encode(raw)

    if encoding == "xor":
        if key is None:
            key = os.urandom(8)
        encoded = xor_encode(raw, key)
        key_hex = key.hex()
        decoder = (
            f"import os;key=bytes.fromhex('{key_hex}');"
            f"exec(bytes(d[i]^key[i%len(key)]for i in range(len(d))))"
        )
        return f"# XOR Key: {key_hex}\n# Decoder stub:\n# {decoder}\n{b64_encode(encoded)}"

    if encoding == "rc4":
        if key is None:
            key = os.urandom(16)
        encoded = rc4(raw, key)
        return f"# RC4 Key: {key.hex()}\n{b64_encode(encoded)}"

    if encoding == "hex":
        return hex_encode(raw)

    if encoding == "chr":
        return string_obfuscate(payload, "payload")

    if encoding == "double_b64":
        first = base64.b64encode(raw)
        second = base64.b64encode(first)
        return second.decode()

    return payload


