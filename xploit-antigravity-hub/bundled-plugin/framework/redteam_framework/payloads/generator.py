def cli_generate(args):
    """Non-interactive CLI payload generation."""
    if args.type not in PAYLOAD_REGISTRY:
        print(f"[!] Unknown type: {args.type}")
        print(f"    Available: {list(PAYLOAD_REGISTRY.keys())}")
        return

    module = PAYLOAD_REGISTRY[args.type]

    # Build params from CLI args
    params = {}
    if args.host:
        params["host"] = args.host
    if args.port:
        params["port"] = args.port
    if args.password:
        params["password"] = args.password
    if args.url:
        params["url"] = args.url
    if args.command:
        params["command"] = args.command

    # Generate
    try:
        if args.variant:
            payload = module.generate(**params, language=args.variant)
        else:
            payload = module.generate(**params)
    except TypeError as e:
        print(f"[!] Generation error: {e}")
        print(f"    Check required parameters for {args.type}")
        return

    # Encode
    if args.encoding and args.encoding != "none":
        key = bytes.fromhex(args.key) if args.key else None
        payload = apply_encoding(payload, args.encoding, key)

    # Output
    if args.output:
        metadata = {
            "type": args.type,
            "variant": args.variant or "default",
            "encoding": args.encoding or "none",
        }
        save_payload(payload, args.output, metadata)
    else:
        print(payload)


def list_all():
    """List all available payloads and variants."""
    print("\n  ==========================================")
    print("  |     THE FORGE - PAYLOAD ARSENAL          |")
    print("  ==========================================\n")

    for name, module in PAYLOAD_REGISTRY.items():
        variants = module.list_variants() if hasattr(module, "list_variants") else ["default"]
        print(f"  [{name}]")
        for v in variants:
            print(f"    |-- {v}")
        print()


